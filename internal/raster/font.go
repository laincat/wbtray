// TextWidth reports how many canvas units a string occupies at a given pixel
// size, with the one-pixel gap between glyphs.
func TextWidth(s string, px float64) float64 {
	if len(s) == 0 {
		return 0
	}
	return (float64(len([]rune(s))*(glyphW+1)) - 1) * px
}

// TextHeight is the height of a line at a given pixel size.
func TextHeight(px float64) float64 { return glyphH * px }

// Text draws s with its top-left corner at x, y where each font pixel is a
// px×px square. Unknown runes are drawn as blanks.
func (c *Canvas) Text(x, y, px float64, s string, v RGBA) {
	if px <= 0 || v.A == 0 {
		return
	}
	cx := x
	for _, r := range s {
		if r >= 'a' && r <= 'z' {
			r -= 32
		}
		g, ok := glyphs[r]
		if !ok {
			cx += (glyphW + 1) * px
			continue
		}
		for row := 0; row < glyphH; row++ {
			line := g[row]
			for col := 0; col < glyphW && col < len(line); col++ {
				if line[col] == '1' {
					c.Rect(cx+float64(col)*px, y+float64(row)*px, px, px, v)
				}
			}
		}
		cx += (glyphW + 1) * px
	}
}
